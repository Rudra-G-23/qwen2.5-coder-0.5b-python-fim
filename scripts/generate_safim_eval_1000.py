#!/usr/bin/env python
"""
scripts/generate_safim_eval_1000.py
Phase A entrypoint: build the fixed, never-retrained-on `safim_eval_1000`
FIM evaluation set. Randomly selects ~750 files from
`stack_v3_python_only_data_without_fim` — a pool that continues the 10k
pilot's stack-v3-train stream past sample_filtered_data_10000's final
checkpoint (shard 9 / row 13500), so it is disjoint from the pilot by
stream position and by content hash (see
configs/data/stack_v3_eval_pool_no_fim.yaml's continue_from_path_prefix) —
buckets them, and samples exactly the literal per-bucket quota in
configs/data/safim_eval_1000.yaml (sums to 1000), pushing the result to
`experiment/safim_eval_1000/` in the HF dataset repo.

Idempotent by design: once `experiment/safim_eval_1000/metadata.json` exists,
re-running this script is a no-op unless --force is passed. This eval set
must never silently change once it's been used to compare models — a
different random draw on a re-run would break that comparison's validity.

Usage:
    python scripts/generate_safim_eval_1000.py
    python scripts/generate_safim_eval_1000.py --config configs/data/safim_eval_1000.yaml
    python scripts/generate_safim_eval_1000.py --force   # deliberately regenerate (rare)
"""

from __future__ import annotations

import argparse
import os
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # make `src` importable

import yaml

from src.fim.ast_bucketer import write_experiment_metadata_json
from src.fim.distribution_planned import sample_fixed_bucket_counts
from src.fim.experiment_io import (
    folder_metadata_exists,
    load_curated_files,
    push_metadata,
    push_variant,
)


def load_config(config_path: str) -> dict:
    with open(config_path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def select_source_files(files: list[dict], sample_size: int, seed: int) -> list[dict]:
    """Randomly select up to `sample_size` files (the ~500-1000 "completely
    new files" the eval task quota is then bucketed from) — never more than
    the pool actually has. Every file in the pool is already post-row-13500
    in the pilot's stream, so "completely new" holds by construction."""
    return random.Random(seed).sample(files, min(sample_size, len(files)))


def run(config: dict, token: str | None, force: bool) -> None:
    hf_repo = config["output"]["hf_dataset_repo"]
    folder = config["output"]["folder"]

    if not force and folder_metadata_exists(hf_repo, folder, token):
        print(
            f"✓ {folder}/metadata.json already exists — skipping regeneration "
            f"(fixed eval set, never regenerated by default). Pass --force to override."
        )
        return

    files = load_curated_files(
        config["source"]["hf_dataset_repo"], config["source"]["path_prefix"], token
    )
    print(f"Loaded {len(files)} curated files from "
          f"{config['source']['hf_dataset_repo']}/{config['source']['path_prefix']}")

    sampled_files = select_source_files(
        files, config["sampling"]["source_file_count"], config["sampling"]["seed"]
    )
    print(f"Selected {len(sampled_files)} files never in the original 10k sample")

    records, shortfall = sample_fixed_bucket_counts(
        sampled_files,
        bucket_counts=config["bucket_quota"],
        max_spans_per_file=config["sampling"]["max_spans_per_file"],
        seed=config["sampling"]["seed"],
    )
    # Stable, index-based task_id — this fixed set is never regenerated, so a
    # simple positional id is sufficient. build_fim_record's general schema
    # has no natural unique-per-span key (multiple spans can share one
    # content_id), so this is minted here rather than upstream.
    for i, rec in enumerate(records):
        rec["task_id"] = f"safim_eval_{i:04d}"

    print(f"Generated {len(records)} FIM eval tasks (target: {sum(config['bucket_quota'].values())})")
    if shortfall:
        print(f"⚠  shortfall vs. bucket_quota: {shortfall}")

    push_variant(records, hf_repo, folder, config["output"]["config_name"], token)
    meta_path = write_experiment_metadata_json(
        "safim_eval_1000",
        records,
        {
            **config["sampling"],
            "bucket_quota": config["bucket_quota"],
            "source_file_count": len(sampled_files),
        },
        shortfall,
        stage_label="Fixed FIM eval set (safim_eval_1000) — held-out, never trained on",
        checkpoints_note=(
            "empty — single in-memory pass over the sampled files (seconds-to-minutes), "
            "nothing to resume; regeneration is guarded by an idempotency check in "
            "scripts/generate_safim_eval_1000.py (--force only) since this set must "
            "never change once used for evaluation"
        ),
    )
    push_metadata(hf_repo, folder, meta_path, token)
    print(f"\n✓ {folder} pushed → {hf_repo}")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build the fixed safim_eval_1000 FIM evaluation set (idempotent)."
    )
    parser.add_argument(
        "--config", default="configs/data/safim_eval_1000.yaml",
        help="Path to the safim_eval_1000 config.",
    )
    parser.add_argument(
        "--force", action="store_true",
        help="Regenerate even if experiment/safim_eval_1000/metadata.json already "
             "exists — deliberately breaks the fixed-set invariant, use with care.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = _parse_args()
    cfg = load_config(args.config)
    hf_token = os.environ.get("HF_TOKEN")
    if not hf_token:
        raise SystemExit("HF_TOKEN must be set to load the source pool and push the eval set.")
    run(cfg, token=hf_token, force=args.force)
